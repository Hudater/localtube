package dev.hudater.localtube.ui

import android.content.Context
import android.net.Uri
import coil.ImageLoader
import coil.decode.DataSource
import coil.decode.ImageSource
import coil.fetch.FetchResult
import coil.fetch.Fetcher
import coil.fetch.SourceResult
import coil.request.Options
import dev.hudater.localtube.core.filesystem.SourceFileSystem
import dev.hudater.localtube.core.model.SourceType
import dev.hudater.localtube.core.player.LocalTubeMediaItems
import dev.hudater.localtube.core.player.SourceResolver
import okio.buffer
import okio.source

/**
 * Loads a thumbnail whose path is encoded as a `localtube://` URI (the
 * same scheme core-player uses for video playback — see
 * [LocalTubeMediaItems]) through the matching [SourceFileSystem].
 *
 * Without this, Coil's default fetchers only understand content://,
 * file://, and http(s):// — an SMB-hosted thumbnail would silently fail
 * to load. Thumbnails generated by [dev.hudater.localtube.core.data.scan.ThumbnailFallbackGenerator]
 * (the frame-extraction fallback) are cached as plain local files and
 * load via Coil's normal file handling instead — this fetcher only
 * matters for sidecar thumbnails read directly off a source.
 */
class ThumbnailFetcher(
    private val context: Context,
    private val uri: Uri,
    private val fileSystemsByType: Map<SourceType, SourceFileSystem>,
    private val sourceResolver: SourceResolver,
) : Fetcher {

    override suspend fun fetch(): FetchResult {
        val sourceId = LocalTubeMediaItems.sourceIdFrom(uri)
        val relativePath = LocalTubeMediaItems.relativePathFrom(uri)
        val source = sourceResolver.resolve(sourceId)
            ?: error("Unknown source id in thumbnail URI: $uri")
        val fileSystem = fileSystemsByType[source.type]
            ?: error("No SourceFileSystem for type ${source.type}")

        val bytes = fileSystem.openInputStream(source, relativePath)

        return SourceResult(
            source = ImageSource(bytes.source().buffer(), context),
            mimeType = null,
            dataSource = DataSource.NETWORK,
        )
    }

    class Factory(
        private val context: Context,
        private val fileSystemsByType: Map<SourceType, SourceFileSystem>,
        private val sourceResolver: SourceResolver,
    ) : Fetcher.Factory<Uri> {
        override fun create(data: Uri, options: Options, imageLoader: ImageLoader): Fetcher? {
            if (data.scheme != "localtube") return null
            return ThumbnailFetcher(context, data, fileSystemsByType, sourceResolver)
        }
    }
}
